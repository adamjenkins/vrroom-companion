# Renders livekit/livekit.yaml from livekit/livekit.yaml.template and the values in .env.
#
# Usage: scripts/render-livekit-config.sh [--quadlet]
#
#   (no option)  Write livekit/livekit.yaml (for podman compose / docker compose).
#   --quadlet    Write ~/.config/vrroom-companion/livekit.yaml instead (for the Quadlet units).
#
# The output contains the LiveKit API secret: it is written with mode 600 and is git-ignored.
# Run the script again after every change to .env, then restart LiveKit.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="${ROOT}/.env"
TEMPLATE="${ROOT}/livekit/livekit.yaml.template"
OUTPUT="${ROOT}/livekit/livekit.yaml"

usage() {
    sed -n '6,12p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
}

die() {
    printf 'render-livekit-config: %s\n' "$*" >&2
    exit 1
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        --quadlet) OUTPUT="${HOME}/.config/vrroom-companion/livekit.yaml" ;;
        -h|--help) usage; exit 0 ;;
        *) usage >&2; die "unknown option: $1" ;;
    esac
    shift
done

umask 077

[[ -f "${ENV_FILE}" ]] || die "missing ${ENV_FILE} (run scripts/gen-secrets.sh first)"
[[ -f "${TEMPLATE}" ]] || die "missing ${TEMPLATE}"

# Value of KEY in .env (last assignment wins; surrounding quotes removed). Parsed, never sourced.
env_get() {
    local key="$1" line value=''
    while IFS= read -r line || [[ -n "${line}" ]]; do
        line="${line%$'\r'}"
        if [[ "${line}" == "${key}="* ]]; then
            value="${line#*=}"
        fi
    done < "${ENV_FILE}"
    if [[ ${#value} -ge 2 ]]; then
        if [[ "${value:0:1}" == '"' && "${value: -1}" == '"' ]] || [[ "${value:0:1}" == "'" && "${value: -1}" == "'" ]]; then
            value="${value:1:${#value}-2}"
        fi
    fi
    printf '%s' "${value}"
}

SAFE='^[A-Za-z0-9._:-]+$'

NODE_IP="$(env_get LIVEKIT_NODE_IP)"
UDP_START="$(env_get LIVEKIT_UDP_START)"
UDP_END="$(env_get LIVEKIT_UDP_END)"
API_KEY="$(env_get LIVEKIT_API_KEY)"
API_SECRET="$(env_get LIVEKIT_API_SECRET)"

# LIVEKIT_NODE_IP: an IPv4 or IPv6 literal (no host names: LiveKit announces it to browsers).
valid_ipv4() {
    local ip="$1" part
    [[ "${ip}" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}$ ]] || return 1
    IFS=. read -r -a parts <<< "${ip}"
    for part in "${parts[@]}"; do
        [[ "${part}" =~ ^(0|[1-9][0-9]{0,2})$ ]] || return 1
        (( part <= 255 )) || return 1
    done
}
valid_ipv6() {
    local ip="$1"
    [[ "${ip}" == *:*:* || "${ip}" == *::* ]] || return 1
    [[ "${ip}" =~ ^[0-9A-Fa-f:.]+$ ]] || return 1
    [[ ${#ip} -le 45 ]]
}
[[ -n "${NODE_IP}" ]] || die "LIVEKIT_NODE_IP is empty in .env: set it to the IP address browsers use to reach this host"
if ! valid_ipv4 "${NODE_IP}" && ! valid_ipv6 "${NODE_IP}"; then
    die "LIVEKIT_NODE_IP in .env is not an IPv4 or IPv6 address"
fi

# UDP range: 1024 <= start <= end <= 65535.
[[ "${UDP_START}" =~ ^[0-9]{1,5}$ && "${UDP_END}" =~ ^[0-9]{1,5}$ ]] \
    || die "LIVEKIT_UDP_START and LIVEKIT_UDP_END in .env must be port numbers"
UDP_START=$((10#${UDP_START}))
UDP_END=$((10#${UDP_END}))
(( UDP_START >= 1024 && UDP_START <= UDP_END && UDP_END <= 65535 )) \
    || die "the UDP range in .env must satisfy 1024 <= LIVEKIT_UDP_START <= LIVEKIT_UDP_END <= 65535"
if (( UDP_START <= 7881 && 7881 <= UDP_END )) || (( UDP_START <= 7880 && 7880 <= UDP_END )); then
    die "the UDP range in .env must not include the ports 7880 and 7881"
fi

[[ "${API_KEY}" =~ ${SAFE} ]] || die "LIVEKIT_API_KEY in .env is empty or has characters other than letters, digits, '.', '_', ':' and '-'"
[[ "${API_SECRET}" =~ ${SAFE} ]] || die "LIVEKIT_API_SECRET in .env is empty or has characters other than letters, digits, '.', '_', ':' and '-'"
[[ ${#API_SECRET} -ge 32 ]] || die "LIVEKIT_API_SECRET in .env must be at least 32 characters"

# Substitute the markers line by line (no eval, no sed expressions built from values; the values
# were checked against ${SAFE} above, so they cannot break the YAML quoting of the template).
OUTDIR="$(dirname "${OUTPUT}")"
mkdir -p "${OUTDIR}"
tmp="$(mktemp "${OUTPUT}.XXXXXX")"
trap 'rm -f "${tmp}"' EXIT
{
    printf '# GENERATED by scripts/render-livekit-config.sh from livekit/livekit.yaml.template and .env.\n'
    printf '# Contains the LiveKit API secret: do not commit or share. Edit .env and render again.\n'
    while IFS= read -r line || [[ -n "${line}" ]]; do
        line="${line//@LIVEKIT_UDP_START@/${UDP_START}}"
        line="${line//@LIVEKIT_UDP_END@/${UDP_END}}"
        line="${line//@LIVEKIT_NODE_IP@/${NODE_IP}}"
        line="${line//@LIVEKIT_API_KEY@/${API_KEY}}"
        line="${line//@LIVEKIT_API_SECRET@/${API_SECRET}}"
        printf '%s\n' "${line}"
    done < "${TEMPLATE}"
} > "${tmp}"

if grep -Eq '@[A-Z][A-Z0-9_]*@' "${tmp}"; then
    die "the template has a marker this script does not know"
fi

chmod 600 "${tmp}"
mv -f "${tmp}" "${OUTPUT}"
trap - EXIT
printf 'Wrote %s (mode 600). Restart LiveKit to use it.\n' "${OUTPUT}"
